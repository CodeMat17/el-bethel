/**
 * Enrol an accepted applicant once an administrator confirms: Convex creates the
 * pupil and parent records, then a parent without a sign-in gets one with a
 * generated password, returned so the admin can give it to the family.
 */
export interface EnrolResult extends AdminResult {
  /** A new parent sign-in, to give to the family in person. */
  signIn?: { name: string; email: string; username: string; password: string };
}

export async function enrolApplicant(applicationId: string, classId: string): Promise<EnrolResult> {
  const result = await tryMutation(api.admissions.enrol, {
    applicationId: applicationId as Id<"applications">,
    classId: classId as Id<"classes">,
  });
  if (!result.ok) return { ok: false, message: result.message };
  const e = result.data;
  refreshSite(SITE_TAGS.levels);
  const paths =["/portal/admin/admissions", "/portal/admin/students", "/portal/admin/parents", "/portal/admin/users"];
  const enrolled = `Enrolled in ${e.className} as ${e.studentNo}.`;
  if (!e.needsSignIn) return done(`${enrolled} ${e.parentName} already has a sign-in and will see the new child.`, ...paths);

  // Try a few usernames in case the obvious one is taken.
  const password = generatePassword();
  let username = "";
  let signIn: Provisioned = { ok: false, message: "" };
  for (const suffix of ["", String(Math.floor(10 + Math.random() * 90)), String(Math.floor(1000 + Math.random() * 9000))]) {
    username = usernameFor(e.parentName, suffix);
    signIn = await provisionSignIn({
      userId: e.accountId,
      name: e.parentName,
      username,
      email: e.parentEmail,
      roles: ["parent"],
      parentId: e.parentId,
      password,
    });
    if (signIn.ok || !signIn.usernameTaken) break;
  }
  if (!signIn.ok) {
    return done(`${enrolled} The parent's sign-in couldn't be created (${signIn.message}). Create it from the parent's record.`, ...paths);
  }
  return {
    ...done(`${enrolled} Sign-in created for ${e.parentName}.`, ...paths),
    signIn: { name: e.parentName, email: e.parentEmail, username, password },
  };
}

