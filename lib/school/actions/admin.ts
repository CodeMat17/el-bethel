interface SignInInput {
  userId?: Id<"users">;
  name: string;
  username: string;
  email: string;
  roles: Role[];
  studentId?: Id<"students">;
  teacherId?: Id<"teachers">;
  parentId?: Id<"parents">;
  /** Generated by the system; the school hands it over in person. */
  password: string;
}

type Provisioned = { ok: true; userId: Id<"users"> } | { ok: false; message: string; usernameTaken?: boolean };

const WORDS = ["Sun", "Lake", "Star", "Moon", "Tree", "Bird", "Rock", "Leaf", "Wave", "Rain", "Gold", "Blue"];

/** Easy to read out and type, e.g. "Moon-48213-Leaf" (always 15 characters). */
function generatePassword(): string {
  const pick = () => WORDS[randomInt(WORDS.length)];
  return `${pick()}-${randomInt(10000, 100000)}-${pick()}`;
}

/**
 * Create a sign-in: reserve the account in Convex (which checks permissions and
 * the username), create the Clerk user with the password, then link the two.
 * Many families don't check email, so the school gives the password in person.
 */
async function provisionSignIn(input: SignInInput): Promise<Provisioned> {
  const { name, username, email, roles, password } = input;
  if (password.length < 15) return { ok: false, message: "The password must be at least 15 characters." };

  const prepared = await tryMutation(api.users.prepareAccount, {
    userId: input.userId,
    name,
    username,
    email,
    roles,
    studentId: input.studentId,
    teacherId: input.teacherId,
    parentId: input.parentId,
  });
  if (!prepared.ok) return { ok: false, message: prepared.message, usernameTaken: /username/i.test(prepared.message) };
  const { userId, created } = prepared.data;

  const [firstName, ...rest] = name.replace(/^(Mrs|Mr|Miss|Dr|Mme|Prof)\.?\s+/i, "").split(/\s+/);
  let clerkUserId: string | null = null;
  try {
    const client = await clerkClient();
    const user = await client.users.createUser({
      username,
      password,
      firstName,
      lastName: rest.join(" ") || undefined,
      emailAddress: [email],
      externalId: userId,
    });
    clerkUserId = user.id;
  } catch (error) {
    await tryMutation(api.users.discardPreparedAccount, { userId, created });
    const message = clerkMessage(error);
    return { ok: false, message, usernameTaken: /username/i.test(message) };
  }

  const linked = await tryMutation(api.users.linkClerkUser, { userId, clerkUserId });
  if (!linked.ok) {
    try {
      await (await clerkClient()).users.deleteUser(clerkUserId);
    } catch (error) {
      console.error("Could not roll back Clerk user", clerkUserId, error);
    }
    await tryMutation(api.users.discardPreparedAccount, { userId, created });
    return { ok: false, message: linked.message };
  }
  return { ok: true, userId };
}

export async function createLogin(formData: FormData): Promise<AdminResult> {
  const name = str(formData, "name");
  const email = str(formData, "email").toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return { ok: false, message: "Enter a valid email address to sign in with." };
  const result = await provisionSignIn({
    userId: opt(formData, "userId") as Id<"users"> | undefined,
    name,
    username: str(formData, "username").toLowerCase(),
    email,
    roles: formData.getAll("roles").map(String) as Role[],
    studentId: opt(formData, "studentId") as Id<"students"> | undefined,
    teacherId: opt(formData, "teacherId") as Id<"teachers"> | undefined,
    parentId: opt(formData, "parentId") as Id<"parents"> | undefined,
    password: String(formData.get("password") ?? ""),
  });
  if (!result.ok) return { ok: false, message: result.message };
  return {
    ...done(`Sign-in created. ${name} can now sign in with ${email} and the password you gave them.`, "/portal/admin", "/portal/admin/users"),
    id: result.userId,
  };
}

